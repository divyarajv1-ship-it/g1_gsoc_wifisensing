#!/usr/bin/env python3
"""Builds Results/figures/*.png and Results/summary_m3.md from the M3 CSV files."""
import json, os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

R = os.path.join(os.path.dirname(__file__), "..", "..", "Results")
FIG = os.path.join(R, "figures")
os.makedirs(FIG, exist_ok=True)
C0, C4 = "#c0392b", "#1f6fb2"
md = ["# M3 results summary (auto-generated by Code/analysis/make_m3_figures.py)", ""]

# ---------------- E8
e8 = pd.read_csv(os.path.join(R, "e8_trigger_timing.csv"))
e8["cfg"] = e8.apply(lambda r: f"rolloff {r.rolloff}" + (f", gap {r.gap}" if r.gap else "") + f", {r.packet_len} B", axis=1)
g = e8.groupby("cfg", sort=False).agg(lost=("lost", "sum"), pdr=("pdr", "mean"), off_min=("off_min", "min"),
                                     off_max=("off_max", "max"), sp_min=("spacing_min", "min"),
                                     sp_max=("spacing_max", "max"), frame=("frame_samples", "first"),
                                     burst=("burst_len", "first"), match=("lost_equals_short_spacing", "all"))
fig, ax = plt.subplots(figsize=(8, 3.6))
y = np.arange(len(g))
ax.hlines(y, g.off_min, g.off_max, color=[C0 if l else C4 for l in g.lost], lw=6)
ax.plot(g.off_min, y, "|", color="k"); ax.plot(g.off_max, y, "|", color="k")
for i, (lab, r) in enumerate(g.iterrows()):
    ax.text(75.3, i, f"lost {int(r.lost)}/2500", va="center", fontsize=8)
ax.set_yticks(y); ax.set_yticklabels(g.index, fontsize=8); ax.invert_yaxis()
ax.set_xlim(68, 78); ax.set_xlabel("trigger position after true burst start (samples)")
ax.set_title("E8: Schmidl & Cox trigger jitter per TX setting (red = packets lost)", fontsize=10)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "fig5_trigger_jitter.png"), dpi=150); plt.close(fig)
md += ["## E8 trigger timing (ideal channel, 500 packets x 5 seeds)", "",
       "| config | lost (sum of 5 seeds) | mean PDR % | trigger offset range | trigger spacing range | frame samples | burst samples | HPD replay predicts every lost packet |",
       "|---|---|---|---|---|---|---|---|"]
for lab, r in g.iterrows():
    md.append(f"| {lab} | {int(r.lost)} | {100*r.pdr:.2f} | {int(r.off_min)}-{int(r.off_max)} | {int(r.sp_min)}-{int(r.sp_max)} | {int(r.frame)} | {int(r.burst)} | {'yes' if r.match else 'no'} |")
md.append("")

# ---------------- E8b
b = pd.read_csv(os.path.join(R, "e8b_length_scan.csv"))
gb = b.groupby("packet_len").agg(lost=("lost", "sum"), jitter=("jitter", "max"), full=("last_symbol_full", "first"),
                                 match=("pred_match", "all"))
fig, ax = plt.subplots(figsize=(8, 3.2))
cols = [C0 if j >= 2 else C4 for j in gb.jitter]
ax.bar([str(i) for i in gb.index], 100 * gb.lost / 900, color=cols)
for i, (pl, r) in enumerate(gb.iterrows()):
    ax.text(i, 100 * r.lost / 900 + 0.15, f"j{int(r.jitter)}", ha="center", fontsize=7)
ax.set_xlabel("packet length (bytes)"); ax.set_ylabel("packets lost (%)")
ax.set_title("E8b: loss vs packet length, rolloff 0 (label = trigger jitter in samples; blue = jitter <= 1)", fontsize=9)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "fig6_length_scan.png"), dpi=150); plt.close(fig)
md += ["## E8b packet-length scan (rolloff 0, ideal channel, 300 packets x 3 seeds)", "",
       "| packet bytes | last payload symbol full? | lost (of 900) | max trigger jitter (samples) | replay predicts losses exactly |", "|---|---|---|---|---|"]
for pl, r in gb.iterrows():
    md.append(f"| {pl} | {'yes' if r.full else 'no'} | {int(r.lost)} | {int(r.jitter)} | {'yes' if r.match else 'no'} |")
md.append("")

# ---------------- E6
e6 = pd.read_csv(os.path.join(R, "e6_multipath_snr.csv"))
e6["snr"] = pd.to_numeric(e6.snr_db, errors="coerce").replace(np.inf, 40).fillna(40)
fig, axs = plt.subplots(1, 4, figsize=(11, 3.2), sharey=True)
for ax, prof in zip(axs, ["flat", "mild", "indoor", "harsh"]):
    for ro, c in ((0, C0), (4, C4)):
        d = e6[(e6.profile == prof) & (e6.rolloff == ro)].groupby("snr").pdr
        m, lo, hi = d.mean(), d.min(), d.max()
        ax.plot(m.index, 100 * m, "o-", color=c, label=f"rolloff {ro}")
        ax.fill_between(m.index, 100 * lo, 100 * hi, color=c, alpha=0.15)
    ax.set_title(prof, fontsize=10); ax.set_xticks([15, 20, 25, 30, 40]); ax.set_xticklabels(["15", "20", "25", "30", "no\nnoise"])
    ax.set_xlabel("SNR (dB)"); ax.grid(alpha=0.3)
axs[0].set_ylabel("PDR (%)"); axs[0].legend(fontsize=8)
fig.suptitle("E6: PDR over static multipath channels (300 packets x 5 seeds; band = min-max)", fontsize=10)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "fig7_multipath_snr.png"), dpi=150); plt.close(fig)
pt = e6.pivot_table(index=["profile", "snr_db"], columns="rolloff", values="pdr", aggfunc="mean")
md += ["## E6 PDR (%) over multipath + AWGN (300 packets x 5 seeds)", "", "| profile | SNR dB | rolloff 0 | rolloff 4 | gain (pp) |", "|---|---|---|---|---|"]
order = {"flat": 0, "mild": 1, "indoor": 2, "harsh": 3}
for (p, s), r in sorted(pt.iterrows(), key=lambda x: (order[x[0][0]], float(x[0][1]) if x[0][1] != "inf" else 99)):
    md.append(f"| {p} | {s} | {100*r[0]:.1f} | {100*r[4]:.1f} | {100*(r[4]-r[0]):+.1f} |")
md.append("")

# ---------------- E7
e7 = pd.read_csv(os.path.join(R, "e7_cfo.csv"))
fig, ax = plt.subplots(figsize=(6, 3.2))
for prof, ls in (("flat", "-"), ("indoor", "--")):
    for ro, c in ((0, C0), (4, C4)):
        m = e7[(e7.profile == prof) & (e7.rolloff == ro)].groupby("cfo_sc").pdr.mean()
        ax.plot(m.index, 100 * m, "o" + ls, color=c, label=f"{prof}, rolloff {ro}")
ax.set_xlabel("carrier frequency offset (subcarrier spacings)"); ax.set_ylabel("PDR (%)")
ax.set_title("E7: PDR vs CFO at 25 dB SNR", fontsize=10); ax.legend(fontsize=7); ax.grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "fig8_cfo.png"), dpi=150); plt.close(fig)
pt = e7.pivot_table(index=["profile", "cfo_sc"], columns="rolloff", values="pdr", aggfunc="mean")
md += ["## E7 PDR (%) vs CFO, SNR 25 dB", "", "| profile | CFO (subcarriers) | rolloff 0 | rolloff 4 |", "|---|---|---|---|"]
for (p, c), r in pt.iterrows():
    md.append(f"| {p} | {c} | {100*r[0]:.1f} | {100*r[4]:.1f} |")
md.append("")

# ---------------- E9
e9 = pd.read_csv(os.path.join(R, "e9_csi_sensing.csv"))
e9["csi_missing"] = 503 - e9.n_csi
fig, axs = plt.subplots(1, 2, figsize=(10, 3.4))
e9["snrn"] = pd.to_numeric(e9.snr_db, errors="coerce").replace(np.inf, np.nan)
noisy = e9[e9.snrn.notna()].copy(); noisy["snr"] = noisy.snrn
for ro, c in ((0, C0), (4, C4)):
    d = noisy[(noisy.rolloff == ro) & noisy.mapped]
    m = d.groupby("snr").nmse_db.mean()
    axs[0].plot(m.index, m, "o-", color=c, label=f"rolloff {ro} (mapped runs)")
    mm = e9[e9.rolloff == ro].copy(); mm["s"] = pd.to_numeric(mm.snr_db, errors="coerce").replace(np.inf, 40).fillna(40)
    k = mm.groupby("s").csi_missing.mean()
    axs[1].plot(k.index, 100 * k / 503, "o-", color=c, label=f"rolloff {ro}")
axs[0].set_xlabel("SNR (dB)"); axs[0].set_ylabel("CSI |H| NMSE (dB)"); axs[0].grid(alpha=0.3); axs[0].legend(fontsize=8)
axs[0].set_title("CSI accuracy from ofdm_chanest_vcvc", fontsize=10)
axs[1].set_xticks([15, 20, 25, 30, 40]); axs[1].set_xticklabels(["15", "20", "25", "30", "no\nnoise"])
axs[1].set_xlabel("SNR (dB)"); axs[1].set_ylabel("frames with no CSI (%)"); axs[1].grid(alpha=0.3); axs[1].legend(fontsize=8)
axs[1].set_title("CSI samples lost by the receiver (time-varying indoor)", fontsize=10)
fig.tight_layout(); fig.savefig(os.path.join(FIG, "fig9_csi.png"), dpi=150); plt.close(fig)
md += ["## E9 CSI for sensing (time-varying indoor channel, 500 packets x 5 seeds, 50 packets/s)", "",
       "| SNR dB | rolloff | mean PDR % | mean frames without CSI (of 503) | runs mapped | mean CSI NMSE dB (mapped) | motion-freq error, seq timestamps (%) | motion-freq error, naive timestamps (%) |",
       "|---|---|---|---|---|---|---|---|"]
e9["err_seq"] = 100 * (e9.f_seq - e9.f_true_amp).abs() / e9.f_true_amp
e9["err_naive"] = 100 * (e9.f_naive - e9.f_true_amp).abs() / e9.f_true_amp
for (s, ro), d in e9.groupby(["snr_db", "rolloff"], sort=False):
    dm = d[d.mapped]
    nm = f"{dm.nmse_db.mean():.1f}" if len(dm) and str(s) != "inf" else ("< -60 (noise-free)" if len(dm) else "-")
    es = f"{dm.err_seq.mean():.2f}" if len(dm) else "-"
    en = f"{dm.err_naive.mean():.2f}" if len(dm) else "-"
    md.append(f"| {s} | {ro} | {100*d.pdr.mean():.1f} | {d.csi_missing.mean():.1f} | {len(dm)}/5 | {nm} | {es} | {en} |")
md.append("")

# ---------------- E10
e10 = pd.read_csv(os.path.join(R, "e10_large_packets.csv"))
md += ["## E10 large packets (20 packets, rolloff 4, ideal channel)", "", "| packet bytes | default buffers | ofdm_tx/ofdm_rx buffers 65536 | + source block 65536 |", "|---|---|---|---|"]
for pl, d in e10.groupby("packet_len"):
    cells = []
    for cfg in ["default", "rx_tx_big", "all_big"]:
        r = d[d.buffers == cfg].iloc[0]
        cells.append("HANG" if r.status == "HANG" else f"{r.status} {int(r.n_rx_valid)}/20")
    md.append(f"| {pl} | " + " | ".join(cells) + " |")
md += ["", "Packets of 1020 bytes or more are never transmitted: `tagged_stream_mux` logs "
       "`requesting more input data than we can provide. ninput_items_required = 12032 max_possible_items_available = 8191` "
       "(1500 B) and the TX outputs nothing, with no exception. 1019 B works (see logs/e10.log and Docs).", ""]
open(os.path.join(R, "summary_m3.md"), "w").write("\n".join(md))
print("\n".join(md))
