#!/usr/bin/env python3
"""M4: one consolidated figure (fig10) and table from the M2/M3 CSV files.
Run from anywhere:  python3 Code/src/analysis/make_m4_summary.py"""
import csv, os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "..", "Results")
M3, M4 = os.path.join(RES, "m3"), os.path.join(RES, "m4")
os.makedirs(M4, exist_ok=True)
load = lambda p: list(csv.DictReader(open(p)))

# E8: ideal channel, 50 B, 5 seeds x 500 packets
e8 = [r for r in load(os.path.join(M3, "e8_trigger_timing.csv")) if r["packet_len"] == "50"]
cfg = [("stock\n(rolloff 0)", "0", "0"), ("rolloff 2", "2", "0"), ("rolloff 4", "4", "0"), ("1 zero\nsample", "0", "1")]
e8_pdr, e8_lost = [], []
for _, ro, gap in cfg:
    rows = [r for r in e8 if r["rolloff"] == ro and r["gap"] == gap]
    lost = sum(int(r["lost"]) for r in rows); sent = sum(int(r["n_tx"]) for r in rows)
    e8_lost.append(lost); e8_pdr.append(100 * (1 - lost / sent))

# E6: noise-free, per multipath profile
e6 = load(os.path.join(M3, "e6_multipath_snr.csv"))
profiles = ["flat", "mild", "indoor", "harsh"]
def mean_pdr(rows):
    return 100 * sum(float(r["pdr"]) for r in rows) / len(rows)
snr_key = [k for k in e6[0] if k.lower().startswith("snr")][0]
inf_rows = [r for r in e6 if r[snr_key] in ("inf", "None", "")]
e6_stock = [mean_pdr([r for r in inf_rows if r["profile"] == p and r["rolloff"] == "0"]) for p in profiles]
e6_fix = [mean_pdr([r for r in inf_rows if r["profile"] == p and r["rolloff"] == "4"]) for p in profiles]

C_STOCK, C_FIX = "#c0392b", "#1f5fa8"
fig, ax = plt.subplots(1, 2, figsize=(10, 4.0))
cols = [C_STOCK, "#e59866", C_FIX, "#5d8fc9"]
b = ax[0].bar([c[0] for c in cfg], e8_pdr, color=cols, width=0.6)
for bar, v, l in zip(b, e8_pdr, e8_lost):
    ax[0].text(bar.get_x() + bar.get_width() / 2, v + 0.15, f"{v:.2f} %\n({l} lost)", ha="center", va="bottom", fontsize=8)
ax[0].set_ylim(94, 101.5); ax[0].set_ylabel("Packet delivery ratio (%)")
ax[0].set_title("(a) Ideal channel, 2500 packets per bar", fontsize=10)
x = range(len(profiles)); w = 0.38
ax[1].bar([i - w / 2 for i in x], e6_stock, w, color=C_STOCK, label="stock TX (rolloff 0)")
ax[1].bar([i + w / 2 for i in x], e6_fix, w, color=C_FIX, label="TX workaround (rolloff 4)")
for i in x:
    ax[1].text(i - w / 2, e6_stock[i] + 0.2, f"{e6_stock[i]:.1f}", ha="center", fontsize=8)
    ax[1].text(i + w / 2, e6_fix[i] + 0.2, f"{e6_fix[i]:.0f}", ha="center", fontsize=8)
ax[1].set_xticks(list(x)); ax[1].set_xticklabels(["flat", "mild\n(35 ns)", "indoor\n(100 ns)", "harsh\n(200 ns)"])
ax[1].set_ylim(85, 102); ax[1].set_title("(b) Noise-free multipath, 1500 packets per bar", fontsize=10)
ax[1].legend(fontsize=8, loc="upper center", bbox_to_anchor=(0.5, -0.2), ncol=2, frameon=False)
for a in ax:
    a.spines[["top", "right"]].set_visible(False); a.grid(axis="y", alpha=0.3)
fig.tight_layout()
fig.savefig(os.path.join(M4, "fig10_consolidated_pdr.png"), dpi=200)

with open(os.path.join(M4, "consolidated_results.md"), "w") as f:
    f.write("# Consolidated headline results (auto-generated by Code/src/analysis/make_m4_summary.py)\n\n")
    f.write("| Setting (ideal channel, 50 B, 5 seeds x 500 packets) | lost | PDR % |\n|---|---|---|\n")
    for (n, _, _), l, p in zip(cfg, e8_lost, e8_pdr):
        f.write(f"| {n.replace(chr(10), ' ')} | {l} | {p:.2f} |\n")
    f.write("\n| Multipath profile, noise-free | stock PDR % | rolloff 4 PDR % |\n|---|---|---|\n")
    for p, s, x4 in zip(profiles, e6_stock, e6_fix):
        f.write(f"| {p} | {s:.1f} | {x4:.1f} |\n")
print(open(os.path.join(M4, "consolidated_results.md")).read())
